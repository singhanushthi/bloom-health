export interface RecipeIngredient {
  /** Key in src/kitchen/ingredients.ts. AI recipes may use an unknown key with `name` set. */
  key: string;
  qty: number;
  unit: Unit;
  optional?: boolean;
  /** Display name when the key isn't in the ingredient list (AI recipes). */
  name?: string;
}

export interface RecipeNutrition {
  kcal: number;
  protein: number;
  carbs: number;
  fat: number;
  fiber: number;
}

export interface Recipe {
  id: string;
  title: string;
  meal: RecipeMeal[];
  diet: DietTag;
  jainOk: boolean;
  timeMin: number;
  servings: number;
  ingredients: RecipeIngredient[];
  steps: string[];
  perServing: RecipeNutrition;
  tags: RecipeTag[];
  tip: string;
  /** 'bloom' = built in; 'ai' = generated by Gemini (estimate); 'mine' = saved by the user. */
  source?: 'bloom' | 'ai' | 'mine';
}

/* ------------------------------ Thresholds ------------------------------ */

export const HIGH_PROTEIN_G = 15;
export const HIGH_FIBRE_G = 6;
export const LOW_OIL_G = 5; // added oil/ghee/butter per serving
export const QUICK_MIN = 20;

const FAT_KEYS = new Set(['oil', 'mustard-oil', 'olive-oil', 'coconut-oil', 'ghee', 'butter']);

const r1 = (n: number) => Math.round(n * 10) / 10;

/** Per-serving nutrition from ingredient amounts (optional ingredients and unknown keys ignored). */
export function computeNutrition(ingredients: RecipeIngredient[], servings: number): RecipeNutrition {
  const t = { protein: 0, carbs: 0, fat: 0, fiber: 0, kcal: 0 };
  for (const i of ingredients) {
    if (i.optional) continue;
    const ing = getIngredient(i.key);
    if (!ing) continue;
    const g = gramsOf(i.key, i.qty, i.unit) / 100;
    t.protein += ing.per100.protein * g;
    t.carbs += ing.per100.carbs * g;
    t.fat += ing.per100.fat * g;
    t.fiber += ing.per100.fiber * g;
    t.kcal += ing.per100.kcal * g;
  }
  const s = Math.max(1, servings);
  return { kcal: Math.round(t.kcal / s), protein: r1(t.protein / s), carbs: r1(t.carbs / s), fat: r1(t.fat / s), fiber: r1(t.fiber / s) };
}

/** Grams of added fat (oil, ghee, butter) per serving. */
export function addedFatPerServing(ingredients: RecipeIngredient[], servings: number): number {
  const g = ingredients.filter((i) => !i.optional && FAT_KEYS.has(i.key)).reduce((s, i) => s + gramsOf(i.key, i.qty, i.unit), 0);
  return r1(g / Math.max(1, servings));
}

/** Vegetarian (veg/vegan) and no onion, garlic or root vegetables — optional ones included. */
export function isJainRecipe(diet: DietTag, ingredients: RecipeIngredient[]): boolean {
  if (diet !== 'veg' && diet !== 'vegan') return false;
  return ingredients.every((i) => !getIngredient(i.key)?.jainAvoid);
}

export function derivedTags(r: Pick<Recipe, 'perServing' | 'timeMin' | 'ingredients' | 'servings'>): RecipeTag[] {
  const tags: RecipeTag[] = [];
  if (r.perServing.protein >= HIGH_PROTEIN_G) tags.push('high-protein');
  if (r.perServing.fiber >= HIGH_FIBRE_G) tags.push('high-fibre');
  if (addedFatPerServing(r.ingredients, r.servings) <= LOW_OIL_G) tags.push('low-oil');
  if (r.timeMin <= QUICK_MIN) tags.push('quick');
  return tags;
}

/** Parse "key qty[unit]; key? qty…" (see header). Throws on malformed specs (caught by tests). */
export function parseSpec(spec: string): RecipeIngredient[] {
  return spec
    .split(';')
    .map((s) => s.trim())
    .filter(Boolean)
    .map((part) => {
      const m = part.match(/^([a-z0-9-]+)(\?)?\s+([\d.]+)\s*(g|ml|pc|tsp|tbsp|cup|pinch)?$/);
      if (!m) throw new Error(`Bad ingredient spec: "${part}"`);
      const out: RecipeIngredient = { key: m[1], qty: Number(m[3]), unit: (m[4] as Unit) ?? 'g' };
      if (m[2]) out.optional = true;
      return out;
    });
}

type Raw = {
  id: string;
  title: string;
  meal: string; // 'b|l|d|s'
  diet: DietTag;
  time: number;
  serves: number;
  ing: string;
  steps: string[];
  tags?: RecipeTag[];
  tip: string;
};

const MEAL_CODE: Record<string, RecipeMeal> = { b: 'breakfast', l: 'lunch', d: 'dinner', s: 'snack' };

function build(r: Raw): Recipe {
  const ingredients = parseSpec(r.ing);
  const perServing = computeNutrition(ingredients, r.serves);
  const base = { perServing, timeMin: r.time, ingredients, servings: r.serves };
  const tags = Array.from(new Set<RecipeTag>([...derivedTags(base), ...(r.tags ?? [])]));
  return {
    id: r.id,
    title: r.title,
    meal: r.meal.split('|').map((c) => MEAL_CODE[c]),
    diet: r.diet,
    jainOk: isJainRecipe(r.diet, ingredients),
    timeMin: r.time,
    servings: r.serves,
    ingredients,
    steps: r.steps,
    perServing,
    tags,
    tip: r.tip,
    source: 'bloom',
  };
}

