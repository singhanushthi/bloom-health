export const RECIPES: Recipe[] = RAW.map(build);

export const RECIPE_BY_ID: ReadonlyMap<string, Recipe> = new Map(RECIPES.map((r) => [r.id, r]));

export function getRecipe(id: string): Recipe | undefined {
  return RECIPE_BY_ID.get(id);
}

/** Quantity scaled to a different number of servings, rounded sensibly for display. */
export function scaleQty(qty: number, unit: Unit, factor: number): number {
  const v = qty * factor;
  if (unit === 'pc' || unit === 'tsp' || unit === 'tbsp' || unit === 'cup' || unit === 'pinch') return Math.max(0.25, Math.round(v * 4) / 4);
  if (v >= 100) return Math.round(v / 5) * 5;
  return Math.max(1, Math.round(v));
}

const FRACTIONS: Record<string, string> = { '0.25': '¼', '0.5': '½', '0.75': '¾' };

/** "1½", "¼", "120". */
export function formatQty(v: number): string {
  const whole = Math.floor(v);
  const frac = Math.round((v - whole) * 100) / 100;
  const f = FRACTIONS[String(frac)];
  if (f) return whole ? `${whole}${f}` : f;
  return String(Math.round(v * 10) / 10);
}

/** "120 g Moong dal", "2 Tomato", "1 tsp Oil", "3 cloves Garlic". */
export function ingredientLine(i: RecipeIngredient, factor = 1): string {
  const ing = getIngredient(i.key);
  const name = ing?.name ?? i.name ?? i.key;
  const q = formatQty(scaleQty(i.qty, i.unit, factor));
  if (i.unit === 'pc') {
    const lbl = ing?.pieceLabel;
    return lbl ? `${q} ${lbl}${scaleQty(i.qty, i.unit, factor) > 1 ? 's' : ''} ${name.toLowerCase()}` : `${q} × ${name}`;
  }
  return `${q} ${i.unit} ${name}`;
}
