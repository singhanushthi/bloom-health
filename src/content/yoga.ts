const TRANSITION_SECONDS = 5;
const LEVEL_RANK: Record<YogaLevel, number> = { beginner: 0, intermediate: 1, advanced: 2 };
const POSE_BY_ID: ReadonlyMap<string, YogaPose> = new Map(POSES.map((p) => [p.id, p]));

/**
 * Total seconds for a session: for each item, (item.seconds ?? pose.holdSeconds) × 2 for
 * per-side poses, plus a 5 s transition. Unknown pose ids count as 0 s hold (+ transition).
 */
export function sessionDurationSeconds(s: YogaSession): number {
  let total = 0;
  for (const item of s.items) {
    const pose = POSE_BY_ID.get(item.poseId);
    const hold = item.seconds ?? pose?.holdSeconds ?? 0;
    total += hold * (pose?.perSide ? 2 : 1) + TRANSITION_SECONDS;
  }
  return total;
}

/**
 * Sessions that suit the user, best first.
 *  - onPeriod → only `periodFriendly` sessions.
 *  - Level: exact level or one level below; never above.
 *  - maxMinutes → only sessions with `minutes <= maxMinutes`.
 *  - Ranking: goal match first, then exact level, then original order.
 */
export function suggestSessions(opts: {
  level: YogaLevel;
  goal?: YogaSession['goal'];
  onPeriod?: boolean;
  maxMinutes?: number;
}): YogaSession[] {
  const want = LEVEL_RANK[opts.level];
  const eligible = SESSIONS.map((s, index) => ({ s, index })).filter(({ s }) => {
    const rank = LEVEL_RANK[s.level];
    if (rank > want || rank < want - 1) return false;
    if (opts.onPeriod && !s.periodFriendly) return false;
    if (opts.maxMinutes !== undefined && s.minutes > opts.maxMinutes) return false;
    return true;
  });
  const score = (s: YogaSession) =>
    (opts.goal && s.goal === opts.goal ? 0 : 2) + (s.level === opts.level ? 0 : 1);
  return eligible
    .sort((a, b) => score(a.s) - score(b.s) || a.index - b.index)
    .map(({ s }) => s);
}

/** Day number for a YYYY-MM-DD key (UTC days since epoch); falls back to a string hash. */
function dayNumber(dateKey: string): number {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(dateKey);
  if (m) {
    const ms = Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3]));
    if (Number.isFinite(ms)) return Math.floor(ms / 86_400_000);
  }
  let h = 0;
  for (let i = 0; i < dateKey.length; i++) h = (h * 31 + dateKey.charCodeAt(i)) | 0;
  return Math.abs(h);
}

/**
 * Deterministic pick for a day: rotates through `suggestSessions` results by date, so
 * consecutive days give different sessions. When a goal is given and some sessions
 * match it, rotation stays within those matches. Always returns a session.
 */
export function todaysSession(opts: {
  level: YogaLevel;
  dateKey: string;
  goal?: YogaSession['goal'];
  onPeriod?: boolean;
}): YogaSession {
  const ranked = suggestSessions({ level: opts.level, goal: opts.goal, onPeriod: opts.onPeriod });
  const goalMatches = opts.goal ? ranked.filter((s) => s.goal === opts.goal) : [];
  let pool = goalMatches.length ? goalMatches : ranked;
  if (!pool.length) {
    // Safety net (should not happen with the shipped content): easiest suitable session.
    pool = SESSIONS.filter(
      (s) => LEVEL_RANK[s.level] <= LEVEL_RANK[opts.level] && (!opts.onPeriod || s.periodFriendly)
    );
    if (!pool.length) pool = SESSIONS.filter((s) => s.periodFriendly);
    if (!pool.length) pool = SESSIONS;
  }
  const n = dayNumber(opts.dateKey);
  return pool[((n % pool.length) + pool.length) % pool.length];
}
