type Item = YogaSession['items'][number];

/** One round of Surya Namaskar (Sun Salutation), 12 movements, `s` seconds per hold. */
function sunSalutationRound(round: number, s: number, opts: { kneesDown?: boolean } = {}): Item[] {
  const note = `Round ${round}`;
  return [
    { poseId: 'prayer', seconds: s, note },
    { poseId: 'upward-salute', seconds: s },
    { poseId: 'standing-forward-fold', seconds: s },
    { poseId: 'low-lunge', seconds: s, note: 'Step one leg back' },
    { poseId: 'plank', seconds: s, note: opts.kneesDown ? 'Knees down is fine' : undefined },
    { poseId: 'knees-chest-chin', seconds: s },
    { poseId: 'cobra', seconds: s },
    { poseId: 'downward-dog', seconds: s + 5 },
    { poseId: 'standing-forward-fold', seconds: s, note: 'Step forward to the hands' },
    { poseId: 'upward-salute', seconds: s },
    { poseId: 'mountain', seconds: s },
  ].map((i) => (i.note === undefined ? { poseId: i.poseId, seconds: i.seconds } : i));
}

