/**
 * Yoga content for Bloom: poses, guided sessions and pure selection helpers.
 *
 * Pure data + pure functions only (no React / RN imports) so it can be used by screens,
 * the session player, tests and background logic alike.
 *
 * Writing rules for this file:
 *  - Cues are short, plain-language and original.
 *  - `benefits` describe how a pose tends to feel; no medical, cure or weight-loss claims.
 *  - `avoidDuringPeriod` marks inversions, strong twists, strong core work and kapalbhati.
 *    Such poses never appear in a `periodFriendly` session.
 */

export type YogaLevel = 'beginner' | 'intermediate' | 'advanced';

export type YogaFocus =
  | 'flexibility'
  | 'strength'
  | 'balance'
  | 'core'
  | 'back'
  | 'hips'
  | 'relaxation'
  | 'breath'
  | 'digestion'
  | 'cramps';

export interface YogaPose {
  id: string;
  name: string;
  sanskrit: string;
  level: YogaLevel;
  focus: Array<YogaFocus>;
  holdSeconds: number;
  perSide?: true;
  /** 3–6 short, plain-language cues. */
  steps: string[];
  /** One sentence, no medical claims. */
  benefits: string;
  cautions: string[];
  /** Inversions, strong twists / core work, kapalbhati. */
  avoidDuringPeriod?: true;
  /** Easier variation. */
  modification?: string;
}

export interface YogaSession {
  id: string;
  title: string;
  level: YogaLevel;
  minutes: number;
  goal: 'weight_loss' | 'flexibility' | 'strength' | 'stress' | 'morning' | 'evening' | 'period_relief' | 'digestion';
  periodFriendly: boolean;
  items: Array<{ poseId: string; seconds?: number; note?: string }>;
  description: string;
}

